def cluster_glyphs(glyphs, font_metrics=None, width_table=None,
                   width_default=0.55):
    """Cluster glyph indices by baseline y_pt (merge within Y_TOL).

    Per-glyph tight right edge `xe` uses real font advances (font property):
    the recorded dx is origin spacing that may include inter-expression
    spacing (several expressions share one EXTTEXTOUT run), so it must not
    be used for box extents or pair-scoring centers.
    """
    gs = sorted((i for i, g in enumerate(glyphs) if "y_pt" in g),
                key=lambda i: glyphs[i]["y_pt"])
    clusters = []
    for i in gs:
        y = glyphs[i]["y_pt"]
        if clusters and abs(clusters[-1]["y"] - y) <= Y_TOL:
            clusters[-1]["idxs"].append(i)
            clusters[-1]["y"] = statistics.median(
                glyphs[j]["y_pt"] for j in clusters[-1]["idxs"])
        else:
            clusters.append({"y": y, "idxs": [i]})
    for c in clusters:
        c["idxs"].sort(key=lambda i: glyphs[i]["x_pt"])
        c["seq"] = "".join(canon(glyphs[i]["ch"]) for i in c["idxs"])
        c["attrs"] = [{"ch": glyphs[i]["ch"], "hex": glyphs[i].get("hex"),
                       "face": glyphs[i].get("font"),
                       "italic": bool(glyphs[i].get("italic"))}
                      for i in c["idxs"]]
        c["xs"] = [glyphs[i]["x_pt"] for i in c["idxs"]]
        c["size_pt"] = statistics.median(
            glyphs[i].get("size_pt") or 0 for i in c["idxs"])

        def tight(i):
            g = glyphs[i]
            r = None
            if font_metrics is not None:
                r = font_metrics.advance_ratio(
                    g["ch"], g.get("hex"), g.get("font"),
                    bool(g.get("italic")))
            if r is None and width_table is not None:
                r = width_table.get(canon(g["ch"]), width_default)
            if r is None:
                r = width_default
            return g["x_pt"] + r * (g.get("size_pt") or c["size_pt"])

        c["xe"] = [tight(i) for i in c["idxs"]]
    return clusters


def find_occurrences(clusters, seq):
    """All (cluster_idx, start_pos) where seq occurs contiguously."""
    out = []
    if not seq:
        return out
    for ci, c in enumerate(clusters):
        start = c["seq"].find(seq)
        while start >= 0:
            out.append((ci, start))
            start = c["seq"].find(seq, start + 1)
    return out


def match_lines(lines, tmpls, clusters, h_rules):
    """Structure-guided matching. Returns {line_nid: (cluster_idx, start)}.

    Pass 1: fraction num/den slot LINEs as pairs (num band above den band,
    minimal x-center distance, bonus when a real fraction bar lies between
    the bands and overlaps the pair span). Pass 2: remaining LINEs,
    longest-sequence-first greedy over free occurrences.
    """
    used = [bytearray(len(c["idxs"])) for c in clusters]
    occ = {ln["nid"]: find_occurrences(clusters, ln["seq"])
           for ln in lines if ln["seq"]}
    line_by_nid = {ln["nid"]: ln for ln in lines}
    mapping = {}

    def free(ci, start, n):
        return all(not used[ci][start + k] for k in range(n))

    def claim(ci, start, n):
        for k in range(n):
            used[ci][start + k] = 1

    def xcenter(ci, start, n):
        c = clusters[ci]
        return (c["xs"][start] + c["xe"][start + n - 1]) / 2.0

    def rule_between(y_num, y_den, xl, xr):
        """A real bar between the bands, mostly contained in the pair span."""
        for r in h_rules:
            ry = r["y1_pt"]
            rx1, rx2 = sorted((r["x1_pt"], r["x2_pt"]))
            if not (min(y_num, y_den) < ry < max(y_num, y_den)):
                continue
            span = xr - xl
            if span <= 0 or not (xl <= (rx1 + rx2) / 2 <= xr):
                continue
            ov = min(xr, rx2) - max(xl, rx1)
            if ov > 0.5 * min(span, rx2 - rx1):
                return True
        return False

    # pass 1: fraction slot pairs
    for t in tmpls:
        if t["selectorName"] != "tmFRACT" or len(t["slot_lines"]) != 2:
            continue
        num_nid, den_nid = t["slot_lines"]
        if num_nid not in occ or den_nid not in occ:
            continue
        n_seq = line_by_nid[num_nid]["seq"]
        d_seq = line_by_nid[den_nid]["seq"]
        best, best_score = None, None
        for nci, ns in occ[num_nid]:
            if not free(nci, ns, len(n_seq)):
                continue
            for dci, ds in occ[den_nid]:
                if dci == nci or not free(dci, ds, len(d_seq)):
                    continue
                if clusters[nci]["y"] >= clusters[dci]["y"]:
                    continue
                xl = min(clusters[nci]["xs"][ns], clusters[dci]["xs"][ds])
                xr = max(clusters[nci]["xe"][ns + len(n_seq) - 1],
                         clusters[dci]["xe"][ds + len(d_seq) - 1])
                score = abs(xcenter(nci, ns, len(n_seq))
                            - xcenter(dci, ds, len(d_seq)))
                if rule_between(clusters[nci]["y"], clusters[dci]["y"], xl, xr):
                    score *= 0.2  # prefer pairs anchored on a real bar
                if best_score is None or score < best_score:
                    best_score = score
                    best = ((nci, ns), (dci, ds))
        if best:
            mapping[num_nid] = best[0]
            mapping[den_nid] = best[1]
            claim(best[0][0], best[0][1], len(n_seq))
            claim(best[1][0], best[1][1], len(d_seq))

    # pass 2: root LINE first, then the rest (longest seq first)
    rest = [ln for ln in lines if ln["seq"] and ln["nid"] not in mapping]
    rest.sort(key=lambda ln: (ln["parent_tmpl"] is not None, -len(ln["seq"])))
    for ln in rest:
        cands = [(ci, s) for ci, s in occ.get(ln["nid"], [])
                 if free(ci, s, len(ln["seq"]))]
        if not cands:
            continue
        # prefer the candidate closest in x to already-matched siblings
        chosen = cands[0]
        mapping[ln["nid"]] = chosen
        claim(chosen[0], chosen[1], len(ln["seq"]))
    return mapping


