    print(f"formulas={n_images} fractions={len(all_meas)} skipped={len(skipped)} "
          f"quarantined={len(quarantined)} bad_line_formulas={len(bad_lines)}")
    for bucket, e in val_report.items():
        gn = e.get("gap_num_bar_absres", {})
        print(f"  {bucket}: n_val={e['n_val']} gap_num_bar absres "
              f"median={gn.get('median')} p95={gn.get('p95')}")
