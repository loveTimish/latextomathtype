CANON = {
    "-": "−", "‐": "−", "–": "−", "—": "−", "−": "−",
    "‘": "'", "’": "'", "′": "'",
}

# baseline clustering tolerance in pt (same band shares an exact y)
Y_TOL = 0.5


def canon(ch: str) -> str:
    return CANON.get(ch, ch)


# ---------------------------------------------------------------------------
# AST flattening: LINE nodes with DIRECT char sequences
# ---------------------------------------------------------------------------

def ast_char_text(node: dict) -> str:
    mc = node.get("mtcode")
    if mc is not None and 0x20 <= mc < 0xD800:
        return canon(chr(mc))
    t = node.get("text") or ""
    if len(t) == 1:
        return canon(t)
    return t


def flatten_ast(root: dict):
    """Returns (lines, tmpls).

    lines: [{nid, seq(direct CHARs only), slot_of{tmpl_nid: slot_index},
             parent_tmpl, depth}]
    tmpls: [{nid, selectorName, variation, slot_lines([nid,...]),
             parent_tmpl, depth}]
    """
    lines: list[dict] = []
    tmpls: list[dict] = []
    counter = [0]

    def direct_seq(node: dict) -> str:
        out = []
        for c in node.get("children") or []:
            if c.get("tag") == "CHAR":
                out.append(ast_char_text(c))
        return "".join(out)

    def walk(node: dict, depth: int, parent_tmpl, slot_of: dict) -> None:
        nid = counter[0]
        counter[0] += 1
        tag = node.get("tag")
        if tag == "LINE":
            lines.append({
                "nid": nid,
                "seq": direct_seq(node),
                "slot_of": dict(slot_of),
                "parent_tmpl": parent_tmpl,
                "depth": depth,
            })
            for c in node.get("children") or []:
                walk(c, depth + 1, parent_tmpl, slot_of)
        elif tag == "TMPL":
            slot_lines = []
            slot_idx = 0
            for c in node.get("children") or []:
                if c.get("tag") == "LINE":
                    child_slot = dict(slot_of)
                    child_slot[nid] = slot_idx
                    before = len(lines)
                    walk(c, depth + 1, nid, child_slot)
                    slot_lines.append(lines[before]["nid"]
                                      if len(lines) > before else None)
                    slot_idx += 1
                else:
                    walk(c, depth + 1, nid, slot_of)
            tmpls.append({
                "nid": nid,
                "selectorName": node.get("selectorName") or "",
                "variation": node.get("variation") or 0,
                "slot_lines": slot_lines,
                "parent_tmpl": parent_tmpl,
                "depth": depth,
            })
        else:
            for c in node.get("children") or []:
                walk(c, depth + 1, parent_tmpl, slot_of)

    walk(root, 0, None, {})
    return lines, tmpls


