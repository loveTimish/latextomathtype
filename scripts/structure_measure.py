def bucket_of(n_fract, n_rules, any_nested):
    if n_fract == 1 and n_rules <= 1:
        return "single"
    if any_nested:
        return "nested"
    if n_rules >= 3:
        return "chain"
    return "multi"


def quantiles(vals):
    vals = sorted(vals)
    if not vals:
        return {}

    def q(p):
        k = (len(vals) - 1) * p
        f = math.floor(k)
        c = min(f + 1, len(vals) - 1)
        return round(vals[f] + (vals[c] - vals[f]) * (k - f), 3)

    return {"n": len(vals), "min": round(vals[0], 3), "p25": q(0.25),
            "median": q(0.5), "p75": q(0.75), "p95": q(0.95),
            "max": round(vals[-1], 3)}


def main() -> int:
    layouts = json.loads(LAYOUTS.read_text(encoding="utf-8"))
    asts = {}
    for line in AST_JSONL.read_text(encoding="utf-8").splitlines():
        rec = json.loads(line)
        if rec.get("ok"):
            asts[Path(rec["path"]).stem] = rec["ast"]

    def split_of(image):
        h = int(hashlib.md5(image.encode()).hexdigest(), 16)
        return "train" if h % 10 < 7 else "val"

    def h_rules_of(rules):
        return [r for r in rules
                if r["kind"] == "line" and abs(r["y1_pt"] - r["y2_pt"]) < 0.2
                and abs(r["x2_pt"] - r["x1_pt"]) > 2.0]

    # pass 0: per-char advance-width table from TRAIN formulas only.
    # Source: dx_pt of glyphs that are NOT last in their EXTTEXTOUT run
    # (the last entry is the advance to the next run, not a width).
    samples: dict[str, list[float]] = {}
    all_ratios: list[float] = []
    for f in layouts["formulas"]:
        image = Path(f["source"]).stem
        if split_of(image) != "train":
            continue
        for g in f["glyphs"]:
            if g.get("last_in_run") or g.get("dx_pt") is None:
                continue
            size = g.get("size_pt") or 0
            if size <= 0:
                continue
            ratio = g["dx_pt"] / size
            if 0.1 < ratio < 1.5:
                samples.setdefault(canon(g["ch"]), []).append(ratio)
                all_ratios.append(ratio)
    width_table = {ch: statistics.median(v) for ch, v in samples.items()}
    width_default = statistics.median(all_ratios) if all_ratios else 0.55
    font_metrics = FontMetrics()

    all_meas, per_formula, skipped = [], [], []
    for f in layouts["formulas"]:
        image = Path(f["source"]).stem
        ast = asts.get(image)
        if ast is None:
            continue
        lines, tmpls = flatten_ast(ast)
        clusters = cluster_glyphs(f["glyphs"], font_metrics,
                                  width_table, width_default)
        line_map = match_lines(lines, tmpls, clusters, h_rules_of(f["rules"]))
        n_lines = sum(1 for ln in lines if ln["seq"])
        n_matched = sum(1 for ln in lines
                        if ln["seq"] and ln["nid"] in line_map)
        meas = measure_formula(image, f["glyphs"], f["rules"], lines, tmpls,
                               line_map, clusters, font_metrics,
                               width_table, width_default)
        for m in meas:
            if "boxes" in m:
                m["boxes"]["wmf_placeable_bbox_pt"] = f.get("placeable_bbox_pt")
            else:
                skipped.append(m)
        n_fract = sum(1 for t in tmpls if t["selectorName"] == "tmFRACT")
        n_rules = sum(1 for r in f["rules"]
                      if r["kind"] == "line" and abs(r["y1_pt"] - r["y2_pt"]) < 0.2
                      and abs(r["x2_pt"] - r["x1_pt"]) > 2.0)
        any_nested = any(t["selectorName"] == "tmFRACT" and t["parent_tmpl"]
                         is not None for t in tmpls)
        bucket = bucket_of(n_fract, n_rules, any_nested)
        split = split_of(image)
        for m in meas:
            if "params" in m:
                m["bucket"] = bucket
                m["split"] = split
        all_meas.extend(m for m in meas if "params" in m)
        pf = {"image": image, "bucket": bucket,
              "n_fract": n_fract, "n_rules": n_rules,
              "line_match": f"{n_matched}/{n_lines}", "split": split}
        # preview-box truth: placeable bbox vs main baseline (five-box
        # semantics: WMF placeable bbox + main baseline, no cross-box claims)
        mb = next((m["boxes"]["main_baseline"] for m in meas
                   if "boxes" in m
                   and m["boxes"].get("main_baseline") is not None), None)
        bbox = f.get("placeable_bbox_pt")
        if bbox and mb is not None:
            pf["box_height_pt"] = round(bbox[3] - bbox[1], 3)
            pf["above_pt"] = round(mb - bbox[1], 3)
            pf["below_pt"] = round(bbox[3] - mb, 3)
        per_formula.append(pf)

    OUT_JSONL.parent.mkdir(parents=True, exist_ok=True)
    with OUT_JSONL.open("w", encoding="utf-8") as fh:
        for m in all_meas:
            fh.write(json.dumps(m, ensure_ascii=False) + "\n")

    param_names = ["bar_overhang_l", "bar_overhang_r",
                   "num_overhang_l", "num_overhang_r",
                   "den_overhang_l", "den_overhang_r",
                   "gap_num_bar", "gap_bar_den", "num_den_gap", "axis_offset"]
    params = {"split": "md5(image)%10<7 -> train (70/30 deterministic)",
              "unit": "pt",
              "width_table_default_ratio": round(width_default, 4),
              "width_table_chars": len(width_table),
              "buckets": {}}
    for bucket in ("single", "nested", "chain", "multi"):
        rows = [m for m in all_meas if m["bucket"] == bucket
                and m["split"] == "train" and "quarantine" not in m]
        if not rows:
            continue
        entry = {"n_train": len(rows)}
        size = statistics.median(r["params"]["size_pt"] for r in rows
                                 if r["params"]["size_pt"])
        entry["size_pt_median"] = round(size, 3)
        for p in param_names:
            vals = [r["params"][p] for r in rows
                    if r["params"].get(p) is not None]
            if not vals:
                continue
            entry[p] = quantiles(vals)
            if size:
                entry[p + "_per_size"] = quantiles([v / size for v in vals])
        params["buckets"][bucket] = entry

    # preview-box truth per bucket (train only): placeable bbox height and
    # its split into above/below the main baseline -- these feed the
    # renderer's FamilyMetrics heights.
    preview_boxes = {}
    for bucket in ("single", "nested", "chain", "multi"):
        rows = [p for p in per_formula if p["bucket"] == bucket
                and p["split"] == "train" and "box_height_pt" in p]
        if not rows:
            continue
        entry = {"n_train": len(rows)}
        for k in ("box_height_pt", "above_pt", "below_pt"):
            entry[k] = quantiles([p[k] for p in rows])
        preview_boxes[bucket] = entry
    params["preview_boxes"] = preview_boxes
    OUT_PARAMS.write_text(json.dumps(params, ensure_ascii=False, indent=1),
                          encoding="utf-8")

    val_report = {}
    for bucket in ("single", "nested", "chain", "multi"):
        tr = params["buckets"].get(bucket)
        if not tr:
            continue
        rows = [m for m in all_meas if m["bucket"] == bucket
                and m["split"] == "val" and "quarantine" not in m]
        entry = {"n_val": len(rows)}
        for p in param_names:
            if p not in tr:
                continue
            med = tr[p]["median"]
            res = [abs(r["params"][p] - med) for r in rows
                   if r["params"].get(p) is not None]
            if res:
                entry[p + "_absres"] = quantiles(res)
        # validation residual for preview box height
        pb = preview_boxes.get(bucket)
        if pb:
            vrows = [p for p in per_formula if p["bucket"] == bucket
                     and p["split"] == "val" and "box_height_pt" in p]
            res = [abs(p["box_height_pt"] - pb["box_height_pt"]["median"])
                   for p in vrows]
            if res:
                entry["box_height_absres"] = quantiles(res)
        val_report[bucket] = entry

    # ---- report ----------------------------------------------------------
    n_images = len(per_formula)
    buckets_c = Counter(p["bucket"] for p in per_formula)
    bad_lines = [p for p in per_formula
                 if p["line_match"].split("/")[0] != p["line_match"].split("/")[1]]
    lines_out = []
    lines_out.append("# 结构参数测量报告（round 4）")
    lines_out.append("")
    lines_out.append("本报告由 `scripts/structure_measure.py` 自动生成，所有数字由脚本计算。")
    lines_out.append("")
    lines_out.append("对齐模型：WMF 字形按字体系输出（非阅读顺序），且同高度的所有分子共享一条基线带、"
                     "所有分母共享另一条。每个 MTEF LINE 对应某基线带内一段连续 x 区间，其 x 排序字符"
                     "序列与 LINE 的直接字符序列完全相等（模板绘制的括号等字形无 AST CHAR，保持未匹配）。"
                     "分式分子/分母槽 LINE 成对匹配（分子带在分母带上方、x 中心距离最小），"
                     "其余 LINE 贪心匹配。恒等为精确字符序列相等，几何从匹配区间读取。")
    lines_out.append("")
    lines_out.append("## 数据概览")
    lines_out.append("")
    lines_out.append(f"- 公式数（WMF 真值 × MTEF AST 配对）：{n_images}")
    lines_out.append(f"- 分式节点测量数（含分数线归属成功）：{len(all_meas)}")
    lines_out.append(f"- 分式节点跳过（LINE 未匹配/槽缺失）：{len(skipped)}")
    lines_out.append(f"- 存在未匹配 LINE 的公式：{len(bad_lines)}")
    if bad_lines:
        lines_out.append(f"  - 示例：{', '.join(p['image'] + '(' + p['line_match'] + ')' for p in bad_lines[:10])}")
    lines_out.append(f"- 结构分桶（按公式）："
                     + ", ".join(f"{k}={v}" for k, v in sorted(buckets_c.items())))
    lines_out.append("")
    lines_out.append("切分：md5(image) % 10 < 7 → train（70/30 确定性切分）。")
    lines_out.append(f"右边缘/紧盒：区间内用原点间距（精确）；区间末字形宽度来自真实字体度量"
                     f"（fontTools 读 times/timesi/symbol.ttf，纯字体属性，无训练泄漏），"
                     f"语料宽度表（{len(width_table)} 字符，默认 {round(width_default, 4)}）仅作回退——"
                     f"因为 MathType 的 dx 是原点间距，多表达式共享运行时含表达式间隙，"
                     f"TA_UPDATECP 末字形 dx 更是到下一运行锚点的距离。")
    lines_out.append("axis_offset 仅对根级分式定义（裸分式或堆叠行内分式为 null/不做结论）。")
    lines_out.append("五框语义分开记录：ink bbox（像素层，TODO）、renderer viewport（不适用）、"
                     "WMF placeable bbox、分子/分母字形盒、基线/数学轴。本报告不做跨框结论。")
    lines_out.append("")
    lines_out.append("## 预览框真值（WMF placeable bbox，train）")
    lines_out.append("")
    lines_out.append("above = 主基线 → bbox 顶；below = 主基线 → bbox 底。供渲染器 FamilyMetrics 高度使用。")
    for bucket, e in preview_boxes.items():
        lines_out.append("")
        lines_out.append(f"### {bucket}（n_train={e['n_train']}）")
        lines_out.append("")
        lines_out.append("| 参数 | p25 | 中位 | p75 | p95 |")
        lines_out.append("|---|---|---|---|---|")
        for k in ("box_height_pt", "above_pt", "below_pt"):
            q = e[k]
            lines_out.append(f"| {k} | {q['p25']} | {q['median']} | {q['p75']} | {q['p95']} |")
        vb = val_report.get(bucket, {}).get("box_height_absres")
