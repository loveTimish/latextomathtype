    lines_out.append("")
    lines_out.append("## 训练集参数（pt，另附 per-size 归一）")
    for bucket, e in params["buckets"].items():
        lines_out.append("")
        lines_out.append(f"### {bucket}（n_train={e['n_train']}, "
                         f"size_pt 中位={e['size_pt_median']}）")
        lines_out.append("")
        lines_out.append("| 参数 | min | p25 | 中位 | p75 | p95 | max | 中位/size |")
        lines_out.append("|---|---|---|---|---|---|---|---|")
        for p in param_names:
            if p not in e:
                continue
            q = e[p]
            ns = e.get(p + "_per_size", {}).get("median")
            lines_out.append(f"| {p} | {q['min']} | {q['p25']} | {q['median']} | "
                             f"{q['p75']} | {q['p95']} | {q['max']} | {ns} |")
    lines_out.append("")
    lines_out.append("## 验证集残差（|实测 − 训练集中位|，pt）")
    for bucket, e in val_report.items():
        lines_out.append("")
        lines_out.append(f"### {bucket}（n_val={e['n_val']}）")
        lines_out.append("")
        lines_out.append("| 参数 | 中位 | p75 | p95 | max |")
        lines_out.append("|---|---|---|---|---|")
        for p in param_names:
            k = p + "_absres"
            if k not in e:
                continue
            q = e[k]
            lines_out.append(f"| {p} | {q['median']} | {q['p75']} | {q['p95']} | {q['max']} |")
    if skipped:
        lines_out.append("")
        lines_out.append("## 跳过的分式节点（需后续处理）")
        lines_out.append("")
        reasons = Counter(m.get("skipped", "?") for m in skipped)
        for reason, n in reasons.most_common():
            lines_out.append(f"- {reason}：{n}")
    quarantined = [m for m in all_meas if "quarantine" in m]
    if quarantined:
        lines_out.append("")
        lines_out.append("## 隔离记录（确定性规则，自动剔除出统计）")
        lines_out.append("")
