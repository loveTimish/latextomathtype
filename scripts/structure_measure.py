def measure_formula(image, glyphs, rules, lines, tmpls, line_map, clusters,
                    font_metrics, width_table, width_default):
    h_rules = [r for r in rules
               if r["kind"] == "line" and abs(r["y1_pt"] - r["y2_pt"]) < 0.2
               and abs(r["x2_pt"] - r["x1_pt"]) > 2.0]
    line_by_nid = {ln["nid"]: ln for ln in lines}

    def glyph_width(attrs, size_pt):
        # true advance from the TTF the glyph came from (font property);
        # fall back to the corpus ratio table, then the global default
        r = font_metrics.advance_ratio(attrs["ch"], attrs["hex"],
                                       attrs["face"], attrs["italic"])
        if r is None:
            r = width_table.get(canon(attrs["ch"]), width_default)
        return r * size_pt

    def geom(nid):
        """(baseline_y, left, right, size_pt) for a matched LINE.

        Right edge: origin spacing inside the matched contiguous range is
        exact; the range-final glyph's width comes from real font metrics
        (its recorded dx is the advance to whatever follows in the run,
        which may be a different expression entirely).
        """
        m = line_map.get(nid)
        if m is None:
            return None
        ci, start = m
        c = clusters[ci]
        n = len(line_by_nid[nid]["seq"])
        right = None
        for p in range(start, start + n):
            if p + 1 < start + n:
                edge = c["xs"][p + 1]
            else:
                edge = c["xs"][p] + glyph_width(c["attrs"][p], c["size_pt"])
            right = edge if right is None else max(right, edge)
        return {"y": c["y"], "left": c["xs"][start],
                "right": round(right, 3) if right is not None else None,
                "size_pt": c["size_pt"]}

    main_baseline = None
    for ln in lines:
        if ln["parent_tmpl"] is None and ln["nid"] in line_map:
            main_baseline = geom(ln["nid"])["y"]
            break
    # no fallback: axis_offset is undefined when the root LINE is unmatched
    # (e.g. the formula is a bare fraction with no top-level chars)

    out = []
    for t in tmpls:
        if t["selectorName"] != "tmFRACT":
            continue
        if len(t["slot_lines"]) != 2 or any(n is None for n in t["slot_lines"]):
            out.append({"image": image, "nid": t["nid"],
                        "skipped": f"slot lines {t['slot_lines']}"})
            continue
        num_nid, den_nid = t["slot_lines"]
        num_g, den_g = geom(num_nid), geom(den_nid)
        if num_g is None or den_g is None:
            out.append({"image": image, "nid": t["nid"],
                        "skipped": "num/den LINE unmatched",
                        "num_seq": line_by_nid[num_nid]["seq"],
                        "den_seq": line_by_nid[den_nid]["seq"]})
            continue

        # visual box of a slot = union of matched ranges of every LINE whose
        # slot chain passes through this TMPL's slot 0 (num) / slot 1 (den)
        def slot_box(slot_idx):
            lefts, rights = [], []
            for ln in lines:
                if ln["slot_of"].get(t["nid"]) != slot_idx:
                    continue
                g = geom(ln["nid"])
                if g is None:
                    continue
                lefts.append(g["left"])
                rights.append(g["right"])
            if not lefts:
                return None
            return {"left": round(min(lefts), 3),
                    "right": round(max(rights), 3), "n": len(lefts)}

        num_box, den_box = slot_box(0), slot_box(1)
        if num_box is None or den_box is None:
            out.append({"image": image, "nid": t["nid"],
                        "skipped": "empty slot box"})
            continue
        lo = min(num_box["left"], den_box["left"])
        hi = max(num_box["right"], den_box["right"])

        best, best_ov = None, 0.0
        for r in h_rules:
            rx1, rx2 = sorted((r["x1_pt"], r["x2_pt"]))
            ry = r["y1_pt"]
            if not (min(num_g["y"], den_g["y"]) - 0.5
                    <= ry <= max(num_g["y"], den_g["y"]) + 0.5):
                continue
            ov = min(hi, rx2) - max(lo, rx1)
            if ov > best_ov:
                best, best_ov = r, ov
        rec = {
            "image": image, "nid": t["nid"], "variation": t["variation"],
            "depth": t["depth"],
            "nested": t["parent_tmpl"] is not None,
            "identity": "exact",
            "boxes": {
                "ink_bbox_px": None,          # pixel layer: TODO
                "renderer_viewport_pt": None,  # N/A for WMF GT
                "wmf_placeable_bbox_pt": None,  # filled by caller
                "num_glyph_box_pt": num_box,
                "den_glyph_box_pt": den_box,
                "num_baseline": round(num_g["y"], 3),
                "den_baseline": round(den_g["y"], 3),
                "main_baseline": (round(main_baseline, 3)
                                  if main_baseline is not None else None),
            },
        }
        if best is not None:
            bar_y = best["y1_pt"]
            bx1, bx2 = sorted((best["x1_pt"], best["x2_pt"]))
            wide_left = min(num_box["left"], den_box["left"])
            wide_right = max(num_box["right"], den_box["right"])
            size = num_g["size_pt"] or den_g["size_pt"]
            rec["bar"] = {"y": round(bar_y, 3), "x1": round(bx1, 3),
                          "x2": round(bx2, 3), "len": round(bx2 - bx1, 3)}
            rec["params"] = {
                "bar_overhang_l": round(wide_left - bx1, 3),
                "bar_overhang_r": round(bx2 - wide_right, 3),
                "num_overhang_l": round(num_box["left"] - bx1, 3),
                "num_overhang_r": round(bx2 - num_box["right"], 3),
                "den_overhang_l": round(den_box["left"] - bx1, 3),
                "den_overhang_r": round(bx2 - den_box["right"], 3),
                "gap_num_bar": round(bar_y - num_g["y"], 3),
                "gap_bar_den": round(den_g["y"] - bar_y, 3),
                "num_den_gap": round(den_g["y"] - num_g["y"], 3),
                # axis_offset is only structurally meaningful for a
                # root-level fraction (main baseline unambiguous)
                "axis_offset": (round(main_baseline - bar_y, 3)
                                if main_baseline is not None
                                and t["parent_tmpl"] is None else None),
                "size_pt": round(size, 3),
            }
            # deterministic quarantine (no manual triage): a fraction whose
            # bar is not mostly inside its slot box, or whose overhang
            # exceeds 5pt (MathType overhang is sub-pt..~2pt), is an x-side
            # matching failure -- excluded from all statistics, listed in
            # the report.
            bar_len = bx2 - bx1
            containment = best_ov / bar_len if bar_len > 0 else 0
            if containment < 0.6:
                rec["quarantine"] = f"bar-not-contained({containment:.2f})"
            elif (abs(rec["params"]["bar_overhang_l"]) > 5
                  or abs(rec["params"]["bar_overhang_r"]) > 5):
                rec["quarantine"] = "overhang-outlier"
        else:
            rec["bar"] = None
        out.append(rec)
    return out


