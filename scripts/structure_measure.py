# -*- coding: utf-8 -*-
"""
Structure-parameter measurement: align MTEF AST structure nodes (from the Go
mtefast exporter) against genuine MathType WMF glyph geometry, cut a ground-
truth box for every fraction template node, and measure micro-structure
parameters (bar overhang, numerator/bar/denominator gaps, math-axis offset).

Alignment model (round 2, derived from corpus evidence):
- MathType WMF emits glyphs grouped by font run, NOT in reading order, and
  NOT one baseline per MTEF LINE: ALL numerators at the same height share
  one baseline band, all denominators share another.
- Each MTEF LINE therefore corresponds to a CONTIGUOUS X-RANGE inside one
  baseline band whose x-sorted char string equals the LINE's direct char
  sequence (template-drawn glyphs like fence parens have no AST CHAR and
  stay unmatched).
- Matching is structure-guided: fraction numerator/denominator slot LINEs
  are matched as PAIRS (num band above den band, minimal x-center distance),
  then the root LINE and remaining LINEs are matched greedily. Identity is
  exact char-sequence equality; geometry is read off the matched range.

Method constraints (from review doc):
- measurements attach to MTEF TMPL nodes (tree-level), not baseline runs.
- train/validation split is deterministic (md5 of image name, 70/30); all
  report numbers are produced by this script (no manual analysis).
- five box semantics recorded separately; no cross-box conclusions.
  ink bbox (pixel layer) is null/TODO; renderer viewport is N/A for WMF GT.

Inputs:
    target/wmf-ruler/glyph-layouts.json   (regenerated by wmf_glyph_layout.py)
    target/wmf-ruler/ast.jsonl            (Go mtefast output)

Outputs:
    target/wmf-ruler/structure-measure.jsonl   per-fraction measurements
    target/wmf-ruler/structure_params.json     train-set median parameters
    docs/structure-params-round1.md            auto-generated report

Usage:
    python scripts/structure_measure.py
"""
